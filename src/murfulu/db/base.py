"""The declarative base, and the column types shared across the tables.

Two things are settled here rather than repeated in every model.

**Constraints are named by a convention.** Without one, Postgres invents names
like ``rules_kind_check`` and Alembic cannot tell one autogenerated migration
from the next, so a later migration silently fails to drop what an earlier one
made. With one, every constraint has the same name on every machine.

**Lists and objects are stored as JSON.** A rule's ``examples`` and a feedback
record's captured context are both variable-shaped, and the alternative — a
Postgres text array — would store a different shape on Postgres than on the
SQLite the offline tests use, so a round trip would prove nothing about the
real database. ``JSONB`` is used where the database supports it.
"""

from __future__ import annotations

from typing import Any

from sqlalchemy import JSON, DateTime, MetaData, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, mapped_column
from sqlalchemy.types import TypeEngine

#: One name per constraint kind, so a constraint is addressable in a migration.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

#: A list or an object, stored as JSONB on Postgres and JSON elsewhere.
Json: TypeEngine[Any] = JSON().with_variant(JSONB, "postgresql")


class Base(DeclarativeBase):
    """Every table in the authored store."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def created_at_column() -> Any:
    """A timestamp the database fills in, so a row cannot arrive undated."""
    return mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )


def one_of(column: str, allowed: tuple[str, ...]) -> str:
    """The SQL for "this column holds one of these values".

    The allowed sets come from the documents that define them — the rule
    loader, ``docs/REVIEW.md`` — so a value the rest of the system cannot
    understand is refused by the database rather than stored and puzzled over
    later.
    """
    listed = ", ".join(f"'{value}'" for value in sorted(allowed))
    return f"{column} IN ({listed})"

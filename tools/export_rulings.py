"""Write ``docs/FOR_THE_LINGUIST.md`` out of the store, and seed the store once.

    python tools/export_rulings.py --seed docs/FOR_THE_LINGUIST.md
    python tools/export_rulings.py --out docs/FOR_THE_LINGUIST.md

**The store is the record and this file is its export** — the project lead's
decision, 2026-08-15. Before it, the questions lived in the Markdown and were
answered in one conversation at the end of a session, which asks someone who
works in Persian to read English Markdown in a repository he does not open.

**Why the document still exists at all.** Two reasons, and neither is habit.
A question and its ruling belong in the git history beside the code they
justify, so a reader six months later finds the reason without a database. And
the repository is the thing that gets reviewed; a decision only a running
service can show is a decision nobody reviews.

**`--seed` runs once per question, and never overwrites.** It reads the handles
out of the existing document and creates any the store does not have, so the
switch loses nothing. A question already in the store is left exactly as it is,
because the store is now the newer of the two.

**The export is generated, so do not edit the file.** Same rule as the rule
pack, which learned it the hard way — see docs/ENGINEERING.md.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from sqlalchemy.orm import Session

from murfulu.db import rulings as store
from murfulu.db.session import session_scope

#: A heading in the document — ``## L13. The grammar and karbon disagree``.
HEADING = re.compile(r"^##\s+(?P<reference>[A-Z]\d{1,3})\.\s+(?P<title>.+?)\s*$")

BANNER = """<!-- Generated by tools/export_rulings.py. Do not edit by hand. -->
<!-- The questions and the rulings live in the app; this is their export.  -->
"""


def _sections(text: str) -> list[tuple[str, str, str]]:
    """Every ``## L13. …`` section: its handle, its title and its body."""
    found: list[tuple[str, str, str]] = []
    reference = title = ""
    body: list[str] = []
    for line in text.splitlines():
        heading = HEADING.match(line)
        if heading:
            if reference:
                found.append((reference, title, "\n".join(body).strip()))
            reference = heading.group("reference")
            title = heading.group("title")
            body = []
        elif reference:
            body.append(line)
    if reference:
        found.append((reference, title, "\n".join(body).strip()))
    return found


def seed(session: Session, document: Path) -> tuple[int, int]:
    """Create a question for every handle the document has and the store lacks.

    Returns (created, left alone). Never edits an existing question: the store
    is the newer of the two from the moment it exists.
    """
    created = skipped = 0
    for reference, title, body in _sections(document.read_text(encoding="utf-8")):
        try:
            store.by_reference(session, reference)
            skipped += 1
            continue
        except store.UnknownQuestionError:
            pass
        store.ask(
            session,
            reference=reference,
            # **The Persian is missing and has to be written.** The document is
            # in English, so seeding cannot invent the question he reads —
            # translating it here would make our English the original. The
            # title stands in until somebody writes the Persian, and the
            # export marks every one that still needs it.
            question_fa=title,
            question_en=title,
            context={"from_document": body} if body else None,
            origin="document",
        )
        created += 1
    return created, skipped


def _render(session: Session) -> str:
    """The document, from the store."""
    lines = [BANNER, "# For the linguist", ""]
    everything = store.questions(session)
    waiting = [q for q in everything if q.state in ("open", "blocked")]
    answered = [q for q in everything if q.state == "answered"]
    withdrawn = [q for q in everything if q.state == "withdrawn"]

    lines += [
        f"**{len(waiting)} waiting, {len(answered)} answered, "
        f"{len(withdrawn)} withdrawn.** Answered in the app, at `/questions`; "
        "this file is the export.",
        "",
    ]

    needs_persian = [q for q in waiting if q.question_fa == q.question_en]
    if needs_persian:
        lines += [
            f"> **{len(needs_persian)} of the waiting questions have no Persian "
            "yet.** They were seeded from this document, which is in English, "
            "and seeding cannot invent the wording he reads — translating it "
            "automatically would make our English the original. Marked ⚠ below.",
            "",
        ]

    for heading, group in (
        ("## Waiting", waiting),
        ("## Answered", answered),
        ("## Withdrawn", withdrawn),
    ):
        if not group:
            continue
        lines += [heading, ""]
        for question in group:
            mark = " ⚠" if question.question_fa == question.question_en else ""
            blocks = " — **blocking**" if question.blocks_work else ""
            title = question.question_en or ""
            lines += [f"### {question.reference}. {title}{mark}{blocks}", ""]
            if question.question_fa and question.question_fa != question.question_en:
                lines += [f"**پرسش:** {question.question_fa}", ""]
            if question.question_latin:
                lines += [f"*{question.question_latin}*", ""]
            choices = store.choices_of(question)
            if choices:
                lines += [
                    f"- `{one['id']}` {one['text_fa']}"
                    + (" *(پیشنهاد ما)*" if one.get("suggested") else "")
                    for one in choices
                ] + [""]
            ruling = store.standing(session, question)
            if ruling:
                if ruling.choice_id:
                    lines += [f"**گزینه:** `{ruling.choice_id}` {ruling.choice_fa}", ""]
                if ruling.ruling_fa != ruling.choice_fa:
                    lines += [f"**پاسخ:** {ruling.ruling_fa}", ""]
                if ruling.ruling_latin:
                    lines += [f"*{ruling.ruling_latin}*", ""]
                if ruling.ruling_en:
                    lines += [f"*Our rendering:* {ruling.ruling_en}", ""]
                if ruling.affects:
                    lines += [f"*Affects:* `{ruling.affects}`", ""]
                history = store.rulings_on(session, question)
                if len(history) > 1:
                    lines += [
                        f"*Ruled {len(history)} times; the answer changed. "
                        "The earlier ones are kept in the app.*",
                        "",
                    ]
            context = question.context or {}
            if isinstance(context, dict) and context.get("withdrawn_because"):
                lines += [f"*Withdrawn:* {context['withdrawn_because']}", ""]
            # **The evidence, carried through verbatim.** A question without
            # the measurement behind it is not answerable, and an export that
            # dropped it would be a worse document than the one it replaced.
            if isinstance(context, dict) and context.get("from_document"):
                lines += [str(context["from_document"]), ""]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    """Seed the store from the document, or write the document from the store."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--seed",
        type=Path,
        help="read the handles out of this document and create any the store lacks",
    )
    parser.add_argument("--out", type=Path, help="write the export here")
    arguments = parser.parse_args(argv)

    if not arguments.seed and not arguments.out:
        parser.error("give --seed, --out, or both")

    with session_scope() as session:
        if arguments.seed:
            created, skipped = seed(session, arguments.seed)
            session.commit()
            print(f"seeded  {created} created, {skipped} already in the store")
        if arguments.out:
            arguments.out.write_text(_render(session), encoding="utf-8")
            print(f"export  {arguments.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
